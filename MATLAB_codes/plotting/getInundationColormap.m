function cmap = getInundationColormap(app)

%%  DEFINE MAP KEYS

keys = { ...
'abyss','sky','autumn','bone','colorcube','cool','copper','flag', ...
'gray','hot','hsv','jet','parula','pink','prism','spring', ...
'summer','turbo','winter', ...
'blue','blue - green','blue - purple','green - blue','greens','grays', ...
'oranges','orange - red','purple - blue','purple - blue -green', ...
'purple - red','purples','red - purple','reds','yellow - green', ...
'yellow - green - blue','yellow - orange - brown','yellow - orange - red', ...
'brown - teal','pink - light green','purple - green','purple - orange', ...
'red - blue','red - gray','red - yellow - blue','red - yellow - green', ...
'spectral','accent','dark 2','paired','pastel 1','pastel 2', ...
'set 1','set 2','set 3'};

keysColor = { ...
'abyss','sky','autumn','bone','colorcube','cool','copper','flag', ...
'gray','hot','hsv','jet','parula','pink','prism','spring', ...
'summer','turbo','winter', ...
'Blues','BuGn','BuPu','GnBu','Greens','Greys','Oranges','OrRd','PuBu','PuBuGn', ...
'PuRd','Purples','RdPu','Reds','YlGn','YlGnBu','YlOrBr','YlOrRd','BrBG','PiYG', ...
'PRGn','PuOr','RdBu','RdGy','RdYlBu','RdYlGn','Spectral','Accent','Dark2','Paired', ...
'Pastel1','Pastel2','Set1','Set2','Set3'};

keysBrewer = { ...
'none','none','none','none','none','none','none','none', ...
'none','none','none','none','none','none','none','none', ...
'none','none','none', ...
'seq','seq','seq','seq','seq','seq','seq','seq','seq','seq', ...
'seq','seq','seq','seq','seq','seq','seq','seq','div','div', ...
'div','div','div','div','div','div','div','div','qual','qual', ...
'qual','qual','qual','qual','qual'};

%%  MAP CONTAINERS
colorMapCM   = containers.Map(keys, keysColor);
colorBrewerCM = containers.Map(keys, keysBrewer);

%%  USER SELECTION
selectedColormap = app.InundationColorMap.Value;

%%  INVALID OPTIONS
invalidSelections = { ...
'--- MATLAB default ----','--- CBREWER 2 ---', ...
'< sequential >','< divergent >','< qualitative >'};

%%  SAFE FALLBACK
if ismember(selectedColormap, invalidSelections) || ...
   ~isKey(colorMapCM, selectedColormap)

    cmap = parula(256);
    return;
end

%%  RESOLVE BASE NAME
baseName   = colorMapCM(selectedColormap);
brewerType = colorBrewerCM(selectedColormap);

%%  MATLAB COLORMAPS
if strcmp(brewerType,'none')

    try
        cmap = feval(baseName, 256);
    catch
        cmap = parula(256);
    end

%%  CBREWER COLORMAPS
else

    try
        cmap = cbrewer2( ...
            brewerType, ...
            baseName, ...
            app.InundationDivisionEditField.Value, ...
            'pchip');
    catch
        cmap = parula(256);
    end

end

%%  OPTIONAL COLORMAP FLIP
if app.InundationColorbar_Flip.Value
    cmap = flipud(cmap);
end
end